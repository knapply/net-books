#!/usr/bin/env python3
"""List every stubbed code tab (TODO(code, ...)) in the book, grouped by chapter.

Usage: python3 tools/pending.py [--md]   (--md writes docs/PENDING.md)
"""
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PAT = re.compile(r"TODO\(code,\s*(\w+)\)[:\s]*(.*)")


def main() -> int:
    found = defaultdict(list)
    for f in sorted((ROOT / "books").rglob("*.qmd")):
        for n, line in enumerate(f.read_text().splitlines(), 1):
            m = PAT.search(line)
            if m:
                found[f.name].append((n, m.group(1), m.group(2).strip()))
    total = sum(len(v) for v in found.values())
    out = [f"# Pending code ({total} stubbed tabs)", ""]
    out.append("Generated by `python3 tools/pending.py --md`. Each line is a tab waiting on a "
               "function knappnet does not expose yet.\n")
    byneed = defaultdict(int)
    for name, items in found.items():
        out.append(f"## {name} ({len(items)})")
        for n, lang, note in items:
            out.append(f"- line {n} [{lang}] {note}")
            byneed[note] += 1
        out.append("")
    text = "\n".join(out)
    if "--md" in sys.argv:
        (ROOT / "docs" / "PENDING.md").write_text(text + "\n")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
