#!/usr/bin/env python3
"""Stamp chapter files and the book's _quarto.yml from outline.toml.

Usage: python3 tools/new_chapters.py books/sna

Chapter and appendix files are created only when missing, so hand-written text
is never overwritten. The book's _quarto.yml is regenerated every run: it holds
nothing but the title, the part structure and the shared settings.
"""
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEMPLATE = (ROOT / "shared" / "templates" / "chapter.qmd").read_text()


def stamp(chapter: dict) -> str:
    return TEMPLATE.format(**chapter)


def write_if_missing(path: Path, text: str) -> bool:
    if path.exists():
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    return True


def main(book_dir: str) -> int:
    book = Path(book_dir)
    outline = tomllib.loads((book / "outline.toml").read_text())
    meta = outline["book"]
    created = 0
    chapter_lines = ["    - index.qmd"]
    number = 0

    for part in outline["part"]:
        chapter_lines.append(f"    - part: \"{part['title']}\"")
        chapter_lines.append("      chapters:")
        for chapter in part["chapter"]:
            number += 1
            rel = f"chapters/{number:02d}-{chapter['slug']}.qmd"
            created += write_if_missing(book / rel, stamp(chapter))
            chapter_lines.append(f"        - {rel}")

    chapter_lines.append("  appendices:")
    for appendix in outline.get("appendix", []):
        rel = f"appendices/{appendix['slug']}.qmd"
        created += write_if_missing(book / rel, stamp(appendix))
        chapter_lines.append(f"    - {rel}")
    chapter_lines.append("    - references.qmd")

    quarto = f"""# Generated by tools/new_chapters.py from outline.toml. Edit the outline.
project:
  type: book
  output-dir: ../../_output/{book.name}

metadata-files:
  - ../../shared/quarto-common.yml

book:
  title: "{meta['title']}"
  subtitle: "{meta['subtitle']}"
  author: "{meta['author']}"
  chapters:
{chr(10).join(chapter_lines[:])}
"""
    (book / "_quarto.yml").write_text(quarto)
    print(f"{book}: {number} chapters, {len(outline.get('appendix', []))} appendices, "
          f"{created} files created")
    return 0


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    sys.exit(main(sys.argv[1]))
