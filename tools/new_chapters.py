#!/usr/bin/env python3
"""Stamp chapter files and the book's _quarto.yml from outline.toml.

Usage: python3 tools/new_chapters.py books/sna

Chapter and appendix files are created only when missing, so hand-written text
is never overwritten. The book's _quarto.yml is regenerated every run: it holds
nothing but the title, the part structure and the shared settings.
"""
import json
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEMPLATE = (ROOT / "shared" / "templates" / "chapter.qmd").read_text()


def stamp(chapter: dict) -> str:
    return TEMPLATE.format(**chapter)


def renumber(path: Path) -> None:
    """If the outline moved a chapter, rename its existing file to the new
    number so written text follows the chapter (matching on the slug)."""
    if path.exists():
        return
    slug = path.name.split("-", 1)[1]
    for old in path.parent.glob(f"[0-9][0-9]-{slug}") if path.parent.exists() else []:
        old.rename(path)


def write_if_missing(path: Path, text: str) -> bool:
    renumber(path)
    if path.exists():
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    return True


def main(book_dir: str) -> int:
    book = Path(book_dir)
    outline = tomllib.loads((book / "outline.toml").read_text())
    meta = outline["book"]
    created = 0
    chapter_lines = ["    - index.qmd"]
    number = 0

    for part in outline["part"]:
        chapter_lines.append(f"    - part: \"{part['title']}\"")
        chapter_lines.append("      chapters:")
        for chapter in part["chapter"]:
            number += 1
            rel = f"chapters/{number:02d}-{chapter['slug']}.qmd"
            created += write_if_missing(book / rel, stamp(chapter))
            chapter_lines.append(f"        - {rel}")

    chapter_lines.append("  appendices:")
    for appendix in outline.get("appendix", []):
        rel = f"appendices/{appendix['slug']}.qmd"
        created += write_if_missing(book / rel, stamp(appendix))
        chapter_lines.append(f"    - {rel}")
    chapter_lines.append("    - references.qmd")

    site = f"https://knapply.github.io/net-books/{book.name}/"
    jsonld = json.dumps({
        "@context": "https://schema.org",
        "@type": "Book",
        "name": meta["title"],
        "alternateName": meta["subtitle"],
        "author": {"@type": "Person", "name": meta["author"]},
        "inLanguage": "en",
        "url": site,
        "isAccessibleForFree": True,
        "license": "https://creativecommons.org/licenses/by-nc-nd/4.0/",
        "encoding": {"@type": "MediaObject", "encodingFormat": "application/json",
                     "contentUrl": site + "machine/book.json"},
    }, indent=2)
    head = "\n".join("          " + line for line in (
        f'<link rel="alternate" type="application/json" href="{site}machine/book.json">\n'
        f'<link rel="alternate" type="text/markdown" href="{site}machine/book.md">\n'
        f'<script type="application/ld+json">\n{jsonld}\n</script>').splitlines())
    quarto = f"""# Generated by tools/new_chapters.py from outline.toml. Edit the outline.
project:
  type: book

metadata-files:
  - ../../shared/quarto-common.yml

bibliography: ../../shared/bib/references.bib

format:
  html:
    css: ../../shared/css/book.css
    include-in-header:
      - text: |
{head}
  pdf:
    include-in-header: ../../shared/tex/print.tex
  epub:
    css: ../../shared/css/book.css

book:
  title: "{meta['title']}"
  subtitle: "{meta['subtitle']}"
  author: "{meta['author']}"
  navbar:
    title: "{meta['author']}"
    background: light
    pinned: true
  page-footer:
    left: "{meta['title']} by {meta['author']}"
    right: "&copy; 2026 {meta['author']} &middot; [CC BY-NC-ND 4.0](https://creativecommons.org/licenses/by-nc-nd/4.0/)"
  site-url: {site}
  repo-url: https://github.com/knapply/net-books
  repo-branch: main
  repo-subdir: books/{book.name}
  repo-actions: [source, issue]
  search: true
  chapters:
{chr(10).join(chapter_lines[:])}
"""
    (book / "_quarto.yml").write_text(quarto)
    print(f"{book}: {number} chapters, {len(outline.get('appendix', []))} appendices, "
          f"{created} files created")
    return 0


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    sys.exit(main(sys.argv[1]))
